async function insertMore() {
  const { data: existing } = await supabase.from('toilets').select('name');
  const existingSet = new Set((existing || []).map(e => e.name.trim().toLowerCase()));

  let count = 0;
  for (const s of ADDITIONAL_SPOTS) {
    if (existingSet.has(s.name.trim().toLowerCase())) continue;

    const payload = {
      name: s.name,
      name_en: s.name_en,
      category: s.category,
      address: s.address,
      province: s.province,
      location: `POINT(${s.lng} ${s.lat})`,
      has_bidet: s.has_bidet,
      wheelchair_accessible: s.wheelchair_accessible,
      elderly_support: s.elderly_support,
      baby_station: s.baby_station,
      has_shower: s.has_shower,
      has_prayer_room: s.has_prayer_room,
      open_24h: s.open_24h,
      is_free: s.is_free,
      price_amount: s.price_amount || 0,
      opening_hours: s.opening_hours,
      overall_rating: s.overall_rating,
      review_count: s.review_count,
      photos: s.photos,
      is_verified: true,
      verification_status: 'verified'
    };

    const { error } = await supabase.from('toilets').insert(payload);
    if (!error) {
      count++;
      console.log(`+ Added: ${s.name}`);
    }
  }

  const { count: total } = await supabase.from('toilets').select('*', { count: 'exact', head: true });
  console.log(`\nDone! Added ${count} iconic spots. Total in DB: ${total}`);
}

insertMore().catch(console.error);
